"""Pure shared-sibling package layout; no qualification or filesystem authority.

The legacy embedded projection remains separate. Callers must bind these bytes
and their explicit layout selection to current contracts and actual native runs.
"""

from __future__ import annotations

import json
import posixpath

from literate_ai.adapters.directory_artifacts import DirectoryExportFile
from literate_ai.contracts.native_cargo_provider_graph import NativeCargoProviderGraph
from literate_ai.contracts.paths import canonical_relative_posix_paths

from .native_cargo_projection import (
    MAX_MANIFEST_BYTES,
    MAX_PROJECTION_BYTES,
    MAX_PROJECTION_FILES,
    NativeCargoProviderSource,
    _digest,
    _encode,
    _manifest,
    _path,
    _require,
)

_RECORD = ".literate/native-cargo/projection.json"
_ORIGINAL = ".literate/native-cargo/original-manifest.toml"
_SCHEMA = "literate-ai/native-cargo-projection@2"
_LAYOUT = "shared-siblings"


def shared_cargo_package_directory(revision):
    """One full revision coordinate, independent of generated bytes and host paths."""
    # Access the typed identity through the same validation as graph construction.
    from literate_ai.contracts.identity import ContentIdentity

    _require(type(revision) is ContentIdentity, "shared_revision")
    return revision.digest


def _inject(original, revision, manifests, graph, nodes):
    value = _manifest(original)
    outgoing = tuple(e for e in graph.edges if e.consumer_revision == revision)
    if not outgoing:
        return original
    dependencies = value.setdefault("dependencies", {})
    aliases = {key.replace("-", "_") for key in dependencies}
    for edge in outgoing:
        _require(edge.alias.replace("-", "_") not in aliases, "conflicting_dependency")
        aliases.add(edge.alias.replace("-", "_"))
        provider = nodes[edge.provider_revision]
        dependencies[edge.alias] = {
            "package": provider.package,
            "version": "=" + provider.version,
            "path": posixpath.relpath(
                posixpath.dirname(manifests[edge.provider_revision]),
                posixpath.dirname(manifests[revision]) or ".",
            ),
        }
    return _encode(value)


def _record(graph, original, manifest):
    payload = (
        json.dumps(
            {
                "schema": _SCHEMA,
                "layout": _LAYOUT,
                "root_manifest": manifest,
                "root_original_manifest_identity": _digest(original).uri,
                "graph": graph.to_dict(),
            },
            sort_keys=True,
            separators=(",", ":"),
        )
        + "\n"
    ).encode()
    _require(len(payload) <= MAX_MANIFEST_BYTES, "projection_record_bound")
    return payload


def _subgraph(graph, revision):
    revisions = {revision}
    pending = [revision]
    while pending:
        consumer = pending.pop()
        for edge in graph.edges:
            if (
                edge.consumer_revision == consumer
                and edge.provider_revision not in revisions
            ):
                revisions.add(edge.provider_revision)
                pending.append(edge.provider_revision)
    return NativeCargoProviderGraph(
        revision,
        tuple(n for n in graph.nodes if n.component_revision in revisions - {revision}),
        tuple(e for e in graph.edges if e.consumer_revision in revisions),
    )


def project_shared_cargo_graph(*, graph, root_manifest, root_manifest_path, sources):
    """Return a root manifest and forest additions preserving every provider byte.

    Each package has its full Component revision as its sibling directory. All
    incoming aliases reach that one package. A provider with native edges must
    already export this layout; legacy embedded exports are never rewritten.
    Returned additions have canonical paths relative to the enclosing forest.
    The caller owns the actual root source and all filesystem/native custody.
    """
    _require(type(graph) is NativeCargoProviderGraph, "graph")
    _path(root_manifest_path)
    root = _manifest(root_manifest)["package"]
    _require(
        type(sources) is tuple
        and all(type(s) is NativeCargoProviderSource for s in sources),
        "sources",
    )
    by_revision = {s.node.component_revision: s for s in sources}
    nodes = {n.component_revision: n for n in graph.nodes}
    _require(
        len(sources) == len(by_revision)
        and set(by_revision) == set(nodes)
        and all(by_revision[r].node == n for r, n in nodes.items()),
        "source_graph",
    )
    _require(
        type(root.get("name")) is str
        and root["name"].replace("-", "_")
        not in {n.package.replace("-", "_") for n in graph.nodes},
        "root_package_collision",
    )
    _require(
        sum(len(s.files) for s in sources) + 2 <= MAX_PROJECTION_FILES
        and sum(len(f.content) for s in sources for f in s.files)
        <= MAX_PROJECTION_BYTES,
        "source_closure_bound",
    )
    directories = {
        revision: shared_cargo_package_directory(revision)
        for revision in (*by_revision, graph.root_revision)
    }
    manifests = {r: directories[r] + "/" + s.manifest for r, s in by_revision.items()}
    manifests[graph.root_revision] = (
        directories[graph.root_revision] + "/" + root_manifest_path
    )
    output = []
    for node in graph.nodes:
        revision = node.component_revision
        source = by_revision[revision]
        files = {f.path: f for f in source.files}
        expected = _inject(source.original_manifest, revision, manifests, graph, nodes)
        _require(files[source.manifest].content == expected, "shared_provider_manifest")
        subtree = _subgraph(graph, revision)
        if subtree.nodes:
            _require(
                _RECORD in files
                and _ORIGINAL in files
                and files[_RECORD].content
                == _record(subtree, source.original_manifest, source.manifest)
                and files[_ORIGINAL].content == source.original_manifest,
                "shared_provider_record",
            )
        else:
            _require(
                _RECORD not in files and _ORIGINAL not in files,
                "shared_provider_record",
            )
        _require(
            not any(
                f.path.startswith(".literate/native-cargo/providers/")
                for f in source.files
            ),
            "shared_embedded_provider",
        )
        output.extend(
            DirectoryExportFile(directories[revision] + "/" + f.path, f.content, f.mode)
            for f in source.files
        )
    if graph.nodes:
        output.extend(
            (
                DirectoryExportFile(
                    directories[graph.root_revision] + "/" + _ORIGINAL,
                    root_manifest,
                    0o644,
                ),
                DirectoryExportFile(
                    directories[graph.root_revision] + "/" + _RECORD,
                    _record(graph, root_manifest, root_manifest_path),
                    0o644,
                ),
            )
        )
    _require(
        len(output) <= MAX_PROJECTION_FILES
        and sum(len(f.content) for f in output) <= MAX_PROJECTION_BYTES,
        "projection_bound",
    )
    canonical_relative_posix_paths(
        [f.path for f in output], label="shared Cargo forest"
    )
    rewritten = _inject(root_manifest, graph.root_revision, manifests, graph, nodes)
    return rewritten, tuple(output)
