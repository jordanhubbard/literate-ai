"""Closed, fixed Cargo compiler-error predicate; no execution or retry grant.

The caller must independently bind metadata, target and generated input bytes to
the original current candidate. Cargo prerequisite failures, arbitrary nonzero
exits and diagnostic text alone are never evidence accepted by this predicate.
"""

import json

MAX_CARGO_JSON_BYTES = 8 * 1024 * 1024
MAX_CARGO_JSON_LINES = 16384
MAX_CARGO_JSON_LINE_BYTES = 1024 * 1024
_SPAN_FIELDS = {
    "file_name",
    "byte_start",
    "byte_end",
    "line_start",
    "line_end",
    "column_start",
    "column_end",
    "is_primary",
    "text",
    "label",
    "suggested_replacement",
    "suggestion_applicability",
    "expansion",
}


def _unique(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError("duplicate Cargo JSON field")
        result[key] = value
    return result


def _primary_span(span, files):
    if (
        type(span) is not dict
        or set(span) != _SPAN_FIELDS
        or span.get("is_primary") is not True
    ):
        return False
    path = span.get("file_name")
    if type(path) is not str or path not in files:
        return False
    content = files[path]
    start, end = span.get("byte_start"), span.get("byte_end")
    if (
        type(content) is not bytes
        or type(start) is not int
        or type(end) is not int
        or not 0 <= start <= end <= len(content)
        or span.get("expansion") is not None
    ):
        return False
    # A real byte range must agree with the reported source lines. No filesystem
    # lookup, absolute-path resolution or compiler execution occurs at replay.
    first = content[:start].count(b"\n") + 1
    last = content[:end].count(b"\n") + 1
    if span.get("line_start") != first or span.get("line_end") != last:
        return False
    lines = content.decode("utf-8").splitlines()
    text = span.get("text")
    if type(text) is not list or len(text) != last - first + 1:
        return False
    for index, line in enumerate(text, first - 1):
        if (
            type(line) is not dict
            or set(line) != {"text", "highlight_start", "highlight_end"}
            or index >= len(lines)
            or line["text"] != lines[index]
            or type(line["highlight_start"]) is not int
            or type(line["highlight_end"]) is not int
            or not 1
            <= line["highlight_start"]
            <= line["highlight_end"]
            <= len(lines[index]) + 1
        ):
            return False
    return True


def cargo_generated_compiler_failure(
    payload, *, returncode, package_id, manifest_path, target, generated_files
):
    """Require a complete failed Cargo build with attributable root errors.

    ``target`` is the exact selected target object from independently validated
    Cargo metadata. ``generated_files`` maps actual compiler span spellings to
    exact captured generated bytes, never dependency/toolchain/build-script files.
    Unsupported diagnostics conservatively return False. The predicate is not a
    complete historical stage verifier or a live repair-eligibility API.
    """
    try:
        if (
            returncode != 101
            or type(returncode) is not int
            or type(payload) is not bytes
            or not payload
            or len(payload) > MAX_CARGO_JSON_BYTES
            or not payload.endswith(b"\n")
            or type(package_id) is not str
            or not package_id
            or type(manifest_path) is not str
            or not manifest_path
            or type(target) is not dict
            or target.get("kind") != ["lib"]
            or target.get("crate_types") not in (["lib"], ["rlib"])
            or type(generated_files) is not dict
            or not generated_files
            or target.get("src_path") not in generated_files
        ):
            return False
        lines = payload.splitlines()
        if not 1 < len(lines) <= MAX_CARGO_JSON_LINES:
            return False
        errors = 0
        finished = False
        for index, line in enumerate(lines):
            if not line or len(line) > MAX_CARGO_JSON_LINE_BYTES or finished:
                return False
            row = json.loads(line, object_pairs_hook=_unique)
            if type(row) is not dict:
                return False
            reason = row.get("reason")
            if reason == "build-finished":
                if (
                    set(row) != {"reason", "success"}
                    or row["success"] is not False
                    or index != len(lines) - 1
                ):
                    return False
                finished = True
            elif reason == "compiler-message":
                if set(row) != {
                    "reason",
                    "package_id",
                    "manifest_path",
                    "target",
                    "message",
                }:
                    return False
                message = row["message"]
                if type(message) is not dict or set(message) != {
                    "rendered",
                    "$message_type",
                    "children",
                    "code",
                    "level",
                    "message",
                    "spans",
                }:
                    return False
                if message["$message_type"] != "diagnostic":
                    return False
                level = message["level"]
                if level == "error":
                    if (
                        row["package_id"] != package_id
                        or row["manifest_path"] != manifest_path
                        or row["target"] != target
                        or type(message["spans"]) is not list
                        or any(
                            type(span) is not dict
                            or set(span) != _SPAN_FIELDS
                            or type(span["is_primary"]) is not bool
                            for span in message["spans"]
                        )
                        or type(message["children"]) is not list
                        or any(
                            type(child) is not dict
                            or child.get("level") not in {"note", "help"}
                            for child in message["children"]
                        )
                    ):
                        return False
                    primary = [
                        span
                        for span in message["spans"]
                        if type(span) is dict and span.get("is_primary") is True
                    ]
                    if not primary or not all(
                        _primary_span(span, generated_files) for span in primary
                    ):
                        return False
                    errors += 1
                elif level not in {"warning", "note", "help", "failure-note"}:
                    return False
            elif reason == "compiler-artifact":
                if set(row) != {
                    "reason",
                    "package_id",
                    "manifest_path",
                    "target",
                    "profile",
                    "features",
                    "filenames",
                    "executable",
                    "fresh",
                }:
                    return False
                if (
                    type(row["target"]) is not dict
                    or "custom-build" in row["target"].get("kind", [])
                    or row["package_id"] == package_id
                    and row["target"] == target
                    or type(row["fresh"]) is not bool
                    or type(row["filenames"]) is not list
                ):
                    return False
            else:
                # Build scripts, non-JSON messages and new protocol variants need
                # separate factual support; they cannot borrow a root error.
                return False
        return finished and errors > 0
    except (ValueError, TypeError, UnicodeError, RecursionError, KeyError):
        return False
